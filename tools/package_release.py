"""Builds the release assets: the addon zip and prebuilt terrain packages, with checksums.

Assets (in --out, default build/release; nothing here goes into git):
    godot-geo-<version>.zip               addons/geo/ with LICENSE, THIRD_PARTY_NOTICES.md and VERSION.txt
    godot-geo-terrain-ankara-40km.zip     terrain/ankara/: 40 x 40 km around Ankara at 10 m (Copernicus DEM,
                                          Sentinel-2 scene pinned below, so a rebuild gives the same data)
    godot-geo-terrain-uskudar-10km.zip    terrain/uskudar_10km/: 10 x 10 km of Üsküdar, Istanbul, with all layers
    godot-geo-terrain-uskudar-60km.zip    terrain/uskudar/: 60 x 60 km around it (both shores, Sabiha Gökçen)
    godot-geo-terrain-samples.zip         terrain/ankara_small, fiji_small, norway_small, uskudar_small (test packages)
    SHA256SUMS.txt
Each terrain zip unpacks into a project as terrain/<name>/ with terrain/.gdignore (the editor must not import the
package files) and an ATTRIBUTION.txt per package made from its terrain.json.

Usage (from the repo root):
    python tools/package_release.py --version 0.1.0                  # addon and samples only (any Python 3)
    tools/.venv/Scripts/python -I tools/package_release.py --version 0.1.0 --terrain
The Ankara and Üsküdar packages are built with tools/build_terrain.py (needs the tools venv and the network or its
cache) unless --ankara / --uskudar-10km / --uskudar-60km name existing packages built with the same arguments.
"""
import argparse
import hashlib
import json
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ADDON = ROOT / "addons" / "geo"
SKIPPED_SUFFIXES = {".import"}  # regenerated by the editor in the user's project
ANKARA_ARGS = ["--lat", "39.9334", "--lon", "32.8597", "--size", "40000", "--spacing", "10",
               "--year", "2025", "--scene", "S2B_36TVK_20250729_0_L2A"]
USKUDAR_LAYERS = ["--scene", "S2A_35TPF_20250722_0_L2A", "--layers", "water,landcover,canopy,buildings,roads"]
USKUDAR_10KM_ARGS = ["--lat", "41.02", "--lon", "29.05", "--size", "10000", "--spacing", "5", "--color-spacing", "10",
                     "--water-spacing", "2.5", *USKUDAR_LAYERS]
USKUDAR_60KM_ARGS = ["--lat", "41.02", "--lon", "29.05", "--size", "60000", "--spacing", "10", "--color-spacing", "10",
                     "--water-spacing", "10", *USKUDAR_LAYERS]
SAMPLES = ["ankara_small", "fiji_small", "norway_small", "uskudar_small"]  # in tests/data/
LAYER_KEYS = ["height", "color", "water", "landcover", "canopy", "buildings", "footprints", "roads"]
ODBL_KEYS = {"water", "buildings", "footprints", "roads"}


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def addon_zip(version: str, out: Path) -> Path:
    target = out / f"godot-geo-{version}.zip"
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for path in sorted(ADDON.rglob("*")):
            if path.is_file() and path.suffix not in SKIPPED_SUFFIXES:
                archive.write(path, "addons/geo/" + path.relative_to(ADDON).as_posix())
        archive.write(ROOT / "LICENSE", "addons/geo/LICENSE")
        archive.write(ROOT / "THIRD_PARTY_NOTICES.md", "addons/geo/THIRD_PARTY_NOTICES.md")
        archive.writestr("addons/geo/VERSION.txt", f"godot-geo {version} (commit {git_commit()})\n"
                         "Documentation and changelog: https://github.com/OWNER/godot-geo\n")
    return target


def git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, check=True, capture_output=True,
                              text=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def check_package(src: Path) -> dict:
    """Reads terrain.json and checks the file hashes it records."""
    meta = json.loads((src / "terrain.json").read_text(encoding="utf-8"))
    if meta.get("format") != "godot-geo-terrain":
        raise ValueError(f"{src}: not a godot-geo terrain package")
    for key in (k for k in LAYER_KEYS if k in meta):
        if sha256(src / meta[key]["file"]) != meta[key]["sha256"]:
            raise ValueError(f"{src}: {meta[key]['file']} does not match the SHA-256 in terrain.json")
    if not meta.get("attribution"):
        raise ValueError(f"{src}: terrain.json has no attribution")
    return meta


def package_files(meta: dict) -> list[str]:
    """terrain.json and every data file it lists (height, colour and the optional layers)."""
    return ["terrain.json"] + [meta[k]["file"] for k in LAYER_KEYS if k in meta]


def attribution_text(name: str, meta: dict) -> str:
    o = meta["origin"]
    lines = [f"Terrain package {name}",
             "",
             f"Origin {o['latitude']}, {o['longitude']}; {meta['size_m'] / 1000:g} x {meta['size_m'] / 1000:g} km; "
             f"heights every {meta['height']['spacing_m']:g} m, colour every {meta['color']['spacing_m']:g} m.",
             f"Built by {meta['generator']} on {meta['created'][:10]}; sources are listed in terrain.json.",
             "",
             "Show these notices wherever the terrain is shown (GeoTerrain.attribution() returns them):",
             ""]
    lines += [f"  {a}" for a in meta["attribution"]]
    if meta.get("disclaimer"):
        lines += ["", meta["disclaimer"]]
    lines += ["",
              "Copernicus DEM GLO-30: free of charge, commercial use permitted under the Copernicus DEM licence.",
              "Copernicus Sentinel-2: full, free and open access under the Copernicus data policy (EU Regulation",
              "1159/2013). The godot-geo MIT licence covers the code only, not this data."]
    odbl = sorted(meta[k]["file"] for k in ODBL_KEYS if k in meta)
    if odbl:
        lines += ["",
                  f"{', '.join(odbl)}: derived from OpenStreetMap (via Overture Maps) and made available under the",
                  "Open Database License 1.0 (https://opendatacommons.org/licenses/odbl/1-0/). Credit:",
                  "\"© OpenStreetMap contributors, Overture Maps Foundation\" (https://www.openstreetmap.org/copyright)."]
    cc = sorted(meta[k]["file"] for k in ("landcover", "canopy") if k in meta)
    if cc:
        lines += ["", f"{', '.join(cc)}: CC BY 4.0 (ESA WorldCover; ETH Global Canopy Height), notices above."]
    lines.append("")
    return "\n".join(lines)


def terrain_zip(target: Path, packages: dict[str, Path]) -> Path:
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as archive:
        archive.writestr("terrain/.gdignore", "")
        for name, src in packages.items():
            meta = check_package(src)
            for f in package_files(meta):
                archive.write(src / f, f"terrain/{name}/{f}")
            archive.writestr(f"terrain/{name}/ATTRIBUTION.txt", attribution_text(name, meta))
    return target


def build_package(out: Path, python: str, name: str, build_args: list[str]) -> Path:
    dest = out / "work" / "terrain" / name
    cmd = [python, "-I", str(ROOT / "tools" / "build_terrain.py"), *build_args, "--out", str(dest)]
    print("building:", " ".join(cmd[2:]), flush=True)
    subprocess.run(cmd, cwd=ROOT, check=True)
    return dest


def checked(src: Path, build_args: list[str]) -> Path:
    """`src` after checking it was built with the origin, size and spacing of `build_args`."""
    meta = check_package(src)
    built = dict(zip(build_args[::2], build_args[1::2]))
    if (meta["origin"]["latitude"], meta["origin"]["longitude"], meta["size_m"],
            meta["height"]["spacing_m"]) != (float(built["--lat"]), float(built["--lon"]),
                                             float(built["--size"]), float(built["--spacing"])):
        raise ValueError(f"{src} was not built with {' '.join(build_args)}")
    return src


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--version", default="dev")
    parser.add_argument("--out", type=Path, default=ROOT / "build" / "release")
    parser.add_argument("--terrain", action="store_true", help="also the Ankara and Üsküdar packages")
    parser.add_argument("--ankara", type=Path, help="existing package to pack instead of building it")
    parser.add_argument("--uskudar-10km", type=Path, help="existing package to pack instead of building it")
    parser.add_argument("--uskudar-60km", type=Path, help="existing package to pack instead of building it")
    parser.add_argument("--python", default=sys.executable, help="interpreter with tools/requirements.txt")
    args = parser.parse_args()

    args.out.mkdir(parents=True, exist_ok=True)
    assets = [addon_zip(args.version, args.out),
              terrain_zip(args.out / "godot-geo-terrain-samples.zip",
                          {n: ROOT / "tests" / "data" / n for n in SAMPLES})]
    jobs = [("ankara", "godot-geo-terrain-ankara-40km.zip", ANKARA_ARGS, args.ankara),
            ("uskudar_10km", "godot-geo-terrain-uskudar-10km.zip", USKUDAR_10KM_ARGS, args.uskudar_10km),
            ("uskudar", "godot-geo-terrain-uskudar-60km.zip", USKUDAR_60KM_ARGS, args.uskudar_60km)]
    for name, asset, build_args, given in jobs:
        if not (args.terrain or given):
            continue
        try:
            src = checked(given or build_package(args.out, args.python, name, build_args), build_args)
            assets.append(terrain_zip(args.out / asset, {name: src}))
        except (ValueError, OSError, subprocess.CalledProcessError) as err:
            print(f"error: {err}", file=sys.stderr)
            return 1

    sums = "".join(f"{sha256(a)}  {a.name}\n" for a in assets)
    (args.out / "SHA256SUMS.txt").write_text(sums, encoding="utf-8", newline="\n")
    for a in assets:
        print(f"{a.name}: {a.stat().st_size / 1e6:.1f} MB")
    print(f"{args.out / 'SHA256SUMS.txt'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
