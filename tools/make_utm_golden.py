"""Generate tests/golden/utm_mgrs_cases.txt, the golden data for GeoMath UTM / MGRS conversions.

Oracles:
  - UTM: pyproj / PROJ (EPSG:326zz north, EPSG:327zz south), which implements the Poder/Engsager extended
    transverse Mercator (nanometre accuracy). The zone number is taken from the MGRS string of the `mgrs` package
    (it applies the Norway and Svalbard exceptions), the hemisphere from the sign of the latitude.
  - MGRS: the `mgrs` Python package (MIT licence), cross-checked here against the pyproj UTM values.
The `mgrs` package is only needed to regenerate this file; tests/python/test_utm_golden.py needs only pyproj.
It is deliberately not in tools/requirements.txt: install it in a throwaway venv (`pip install mgrs pyproj`).

Run from the repo root:  python tools/make_utm_golden.py
Line formats (whitespace separated, `#` comments):
  utm  lat lon zone N|S easting northing        metres, false easting / northing included
  mgrs lat lon digits STRING                    digits per coordinate (5 = 1 m); lower precisions are truncations
"""
import math
import random
import sys
from pathlib import Path

import mgrs
import pyproj

OUT = Path(__file__).resolve().parents[1] / "tests" / "golden" / "utm_mgrs_cases.txt"

NAMED = [
    # Turkey
    (39.9334, 32.8597), (40.1281, 32.9951), (41.0082, 28.9784), (38.4237, 27.1428), (36.8969, 30.7133),
    (41.0027, 39.7168), (40.6013, 43.0975), (37.5744, 43.7408), (41.6771, 26.5557), (42.0231, 35.1531),
    # zone edges (30 E and 36 E)
    (40.0, 29.9999), (40.0, 30.0), (40.0, 30.0001), (40.0, 35.9999), (40.0, 36.0),
    # equator, both sides, and the prime meridian
    (0.0, 0.0), (0.0, -0.0001), (0.0001, 0.0001), (-0.0001, 36.5), (0.0, 179.9999), (0.0, -180.0),
    # southern hemisphere
    (-16.82, 179.99), (-16.82, -179.99), (-33.9249, 18.4241), (-33.8688, 151.2093), (-34.6037, -58.3816),
    # Norway exception (32V)
    (60.5, 5.5), (59.9139, 10.7522), (62.0, 4.0), (56.0, 3.0), (56.0, 2.99), (63.99, 11.99), (55.99, 5.5),
    (64.0, 5.5),
    # Svalbard exceptions (31X, 33X, 35X, 37X)
    (78.0, 15.0), (78.2253, 15.6469), (74.0, 7.0), (71.99, 7.0), (74.0, 8.99), (74.0, 9.0), (75.0, 20.0),
    (75.0, 20.99), (75.0, 21.0), (75.0, 31.0), (75.0, 32.99), (75.0, 33.0), (75.0, 38.0), (80.0, 41.99),
    # northern Norway
    (69.99, 23.27), (69.6492, 18.9553),
    # high / low latitude limits
    (83.99, 0.5), (83.9999, 100.0), (83.5, -170.0), (-80.0, 10.0), (-79.99, -170.0), (-80.0, 179.99), (-79.9, -60.0),
]
RANDOM_COUNT = 20
SEED = 20261101


def main() -> int:
    conv = mgrs.MGRS()
    points = list(NAMED)
    rng = random.Random(SEED)
    while len(points) < len(NAMED) + RANDOM_COUNT:
        points.append((round(rng.uniform(-80.0, 83.99), 6), round(rng.uniform(-180.0, 179.99), 6)))
    transformers: dict[tuple[int, bool], pyproj.Transformer] = {}
    lines = [
        "# Generated by tools/make_utm_golden.py (pyproj for UTM, python-mgrs for MGRS). Do not edit.",
        "# utm  lat lon zone N|S easting northing",
        "# mgrs lat lon digits STRING   (digits 5 shown; lower precisions are truncations of it)",
    ]
    utm_lines, mgrs_lines = [], []
    for lat, lon in points:
        s5 = conv.toMGRS(lat, lon, MGRSPrecision=5)
        zone = int(s5[:2] if s5[1].isdigit() else s5[:1])
        north = lat >= 0.0
        key = (zone, north)
        if key not in transformers:
            epsg = (32600 if north else 32700) + zone
            transformers[key] = pyproj.Transformer.from_crs("EPSG:4326", f"EPSG:{epsg}", always_xy=True)
        e, n = transformers[key].transform(lon, lat)
        # Cross-check the MGRS digits against the pyproj coordinates (truncation) and lower precisions.
        tail = s5[-10:]
        if (int(tail[:5]), int(tail[5:])) != (math.floor(e) % 100000, math.floor(n) % 100000):
            print("MGRS / pyproj mismatch (point too close to a 1 m boundary?):", lat, lon, s5, e, n)
            return 1
        for digits in range(0, 5):
            if conv.toMGRS(lat, lon, MGRSPrecision=digits) != s5[:len(s5) - 10] + (tail[:digits] + tail[5:5 + digits]):
                print("MGRS precision is not truncation:", lat, lon, digits)
                return 1
        utm_lines.append(f"utm {lat!r} {lon!r} {zone} {'N' if north else 'S'} {e:.6f} {n:.6f}")
        mgrs_lines.append(f"mgrs {lat!r} {lon!r} 5 {s5}")
    OUT.write_text("\n".join(lines + utm_lines + mgrs_lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(points)} points)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
